export type PikachuVerticalTiltAction = 'up-tilt' | 'down-tilt';
export function buildPikachuVerticalTiltWithAuthoredHurtboxes(action: PikachuVerticalTiltAction): AttackMoveWithAnimation {
  const poses = PIKACHU_VERTICAL_TILT_AUTHORED_HURTBOX_POSES.filter(row => row.action === action);
  const hurtboxModifiers: MoveHurtboxModifier[] = poses.flatMap(row => row.hurtboxes.map(hurtbox => ({
      frameWindow: { startFrame: row.startElapsed, endFrame: row.endElapsed }, replaceBody: true, hurtbox })));
  const frameWindows = poses.map((row, artFrameIndex) => ({
    startFrame: row.startElapsed, endFrame: row.endElapsed, artFrameIndex }));
  return { ...buildPikachuNormalMove(action, action === 'up-tilt' ? pikachuUpTiltPose : undefined), hurtboxModifiers,
    animation: { startupFrames: 2, activeFrames: action === 'up-tilt' ? 7 : 2,
      recoveryFrames: action === 'up-tilt' ? 3 : 2, frameWindows } };
}
