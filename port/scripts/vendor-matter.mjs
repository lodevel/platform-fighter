// Rebuild the unchanged, committed Phaser 3.90.0 Matter 0.20.0 fork.
// The retired Phaser package is not needed to build or verify the game.
//   node port/scripts/vendor-matter.mjs          rebuild the ES module
//   node port/scripts/vendor-matter.mjs --check  verify source hashes and bundle
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '../..');
const OUT = path.join(ROOT, 'src/physics/matter');
const SOURCE = path.join(OUT, 'source');
const manifest = JSON.parse(fs.readFileSync(path.join(OUT, 'source-sha256.json'), 'utf8'));
const files = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
  entry.isDirectory() ? files(path.join(dir, entry.name)) : [path.join(dir, entry.name)]);
const actual = Object.fromEntries(files(SOURCE).sort().map((file) => [path.relative(SOURCE, file),
  createHash('sha256').update(fs.readFileSync(file)).digest('hex')]));
const bad = Object.keys(manifest.files).filter((file) => actual[file] !== manifest.files[file]);
const extra = Object.keys(actual).filter((file) => !(file in manifest.files));
if (bad.length || extra.length) throw new Error(`Vendored Matter source changed: ${JSON.stringify({ bad, extra })}`);

const result = await build({
  absWorkingDir: path.join(ROOT, 'port'),
  entryPoints: [path.join(SOURCE, 'CustomMain.js')],
  bundle: true, format: 'esm', platform: 'neutral', outfile: path.join(OUT, 'matter.js'), write: false,
  banner: { js: "// GENERATED by port/scripts/vendor-matter.mjs from source/ (Phaser 3.90.0's Matter 0.20.0 fork, MIT). Do not edit." },
  logLevel: 'warning',
});
const bundle = result.outputFiles[0].contents;
if (process.argv.includes('--check')) {
  // The initial bundle predates the gate's move out of port/src/pending.
  // Ignore only esbuild's diagnostic module path labels for that relocation.
  const normalized = (text) => text.replace(/(?:src\/pending|\.\.\/src|src)\/physics\/matter\/source\//g, 'SOURCE/');
  if (normalized(Buffer.from(bundle).toString()) !== normalized(fs.readFileSync(path.join(OUT, 'matter.js'), 'utf8')))
    throw new Error('Vendored Matter bundle is stale; rebuild it with this script.');
  console.log(`Vendored Matter verified: ${Object.keys(actual).length} source files and generated bundle (relocated path labels normalized)`);
} else {
  fs.writeFileSync(path.join(OUT, 'matter.js'), bundle);
  console.log(`Rebuilt vendored Matter from ${Object.keys(actual).length} verified source files`);
}
