#!/usr/bin/env python3
"""Compile preserved source captures without inventing runtime geometry or values."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/review/2026-10-06/pikachu-character/sources/native-attacks.json'
OUTPUT = ROOT / 'src/characters/pikachuAttackData.ts'
capture = json.loads(SOURCE.read_text())
rows = {}
for key, motion in capture['motions'].items():
    for function in motion['functions']:
        if function['name'].startswith('game_') and function['attacks']:
            if key in rows:
                raise ValueError(f'Multiple attack functions for {key}')
            rows[key] = function['attacks']
header = f'''/** Lossless per-region vanilla Ultimate capture. Generated by tools/pikachu-source-compile.py.
 * Revision {capture['script_revision']}; motion frames, not GIF indices.
 * Historical/native discrepancies with UFD remain in the evidence record.
 * Keeping a source field here does not establish that the engine implements it. */
export const PIKACHU_NATIVE_ATTACKS = '''
OUTPUT.write_text(header + json.dumps(rows, ensure_ascii=False, separators=(',', ':'), indent=2) + ' as const;\n')
print(f'Compiled {sum(map(len, rows.values()))} attack regions in {len(rows)} motions')
