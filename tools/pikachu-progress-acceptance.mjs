import { chromium } from 'playwright';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';

const root = path.resolve(import.meta.dirname, '..');
const evidence = path.join(root, 'docs/review/2026-10-06/pikachu-character');
const out = path.join(evidence, 'motion-gallery/live-progress');
mkdirSync(out, { recursive: true });
const url = 'http://127.0.0.1:4195/pikachu-motion-preview.html';
const report = { url, scope: 'Live dashboard, explicit action milestones, filters, automatic refresh and stale-data retention; no fighter acceptance upgrade', cases: [], errors: [] };
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const browser = await chromium.launch({ headless: true, args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
page.on('pageerror', error => report.errors.push(error.message));
try {
  const liveResponse = await fetch(new URL('/pikachu-progress.json', url));
  assert(liveResponse.ok && liveResponse.headers.get('cache-control') === 'no-store', 'Live data must be uncached');
  const live = await liveResponse.json();
  const inventory = JSON.parse(readFileSync(path.join(evidence, 'inventory.json')));
  assert(live.total === inventory.actions.length, 'Every canonical action must be represented');
  assert(live.actions.every(action => !action.progress?.complete || (action.progress.required_gaps.length === 0)), 'Complete rows must have no required gaps');
  report.actualSnapshot = { revision: live.revision, total: live.total, reconciled: live.reconciled, complete: live.complete, counts: live.counts, art: live.art };
  report.galleryBuildSha256 = createHash('sha256').update(readFileSync(path.join(evidence, 'motion-gallery-build.json'))).digest('hex');
  await page.goto(url, { waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => document.querySelector('#live-state').dataset.state === 'live');
  assert(await page.locator('#completion-count').textContent() === `${live.complete} / ${live.total} · ${Math.floor(live.complete / live.total * 100)}%`, 'Wrong completion count');
  assert(await page.locator('#completion-bar').getAttribute('value') === String(live.complete), 'Wrong progress bar');
  assert(await page.locator('#action-list .action').count() === live.total - live.complete, 'Remaining filter omitted actions');
  report.cases.push({ name: 'Live canonical counts and remaining actions', passed: true });
  await page.locator('#action-filter').selectOption('all');
  assert(await page.locator('#action-list .action').count() === live.total, 'All-action filter');
  await page.locator('#action-filter').selectOption('complete');
  assert(await page.locator('#action-list .action').count() === live.complete, 'Completed-action filter');
  await page.locator('#action-filter').selectOption('all');
  await page.locator('#action-search').fill('quick-attack');
  assert(await page.locator('#action-list .action').count() === live.actions.filter(action => [action.id, ...(action.progress?.required_gaps ?? [])].join(' ').toLowerCase().includes('quick-attack')).length, 'Search omitted matching action');
  await page.locator('#action-search').fill('');
  await page.locator('#action-filter').selectOption('remaining');
  report.cases.push({ name: 'Search and all/complete/remaining filters', passed: true });
  assert(await page.locator('[data-page]').count() === 9, 'Existing move navigation lost');
  await page.locator('[data-page="pikachu-back-air-packed-preview.html"]').click();
  const frame = await (await page.locator('#motion').elementHandle()).contentFrame();
  await frame.waitForFunction(() => window.__pikachuBackAirPreview?.ready);
  await frame.locator('#attack').click();
  await frame.locator('#step').click();
  assert((await frame.evaluate(() => window.__pikachuBackAirPreview.state())).elapsed === 1, 'Existing preview frame stepping broken');
  report.cases.push({ name: 'Preserved move navigation and frame controls', passed: true });
  const before = await page.locator('#art-count').textContent();
  const expandedAction = await page.locator('#action-list .action').first().getAttribute('data-action');
  await page.locator('#action-list .action').first().locator('details summary').click();
  const simulated = structuredClone(live);
  simulated.revision = 'simulated-live-refresh';
  simulated.art.cells += 1;
  await page.route('**/pikachu-progress.json', route => route.fulfill({ json: simulated, headers: { 'Cache-Control': 'no-store' } }));
  await page.waitForFunction(expected => document.querySelector('#art-count').textContent === expected, simulated.art.cells.toLocaleString(), { timeout: 12000 });
  assert(await page.locator('#art-count').textContent() !== before, 'Automatic refresh did not update');
  assert(await page.locator(`[data-action="${expandedAction}"] details`).getAttribute('open') !== null, 'Live refresh closed the evidence being read');
  report.cases.push({ name: 'Automatic five-second refresh', passed: true, simulatedResponse: true });
  await page.unroute('**/pikachu-progress.json');
  await page.route('**/pikachu-progress.json', route => route.fulfill({ status: 503, json: { error: 'Simulated writer update' } }));
  await page.locator('#refresh-progress').click();
  await page.waitForFunction(() => document.querySelector('#live-state').textContent === 'Updates paused');
  assert(await page.locator('#art-count').textContent() === simulated.art.cells.toLocaleString(), 'Unavailable data reset counts');
  assert(await page.locator('#progress-error').isVisible(), 'Stale evidence must be visible');
  report.cases.push({ name: 'Unavailable evidence retains last snapshot and marks stale', passed: true, simulatedResponse: true });
  await page.unroute('**/pikachu-progress.json');
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForFunction(() => document.querySelector('#live-state').dataset.state === 'live');
  await page.screenshot({ path: path.join(out, 'desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Mobile page overflows horizontally');
  await page.screenshot({ path: path.join(out, 'mobile.png'), fullPage: true });
  report.cases.push({ name: 'Mobile width has no horizontal overflow', passed: true });
  assert(report.errors.length === 0, 'Browser errors');
  report.status = 'passed';
} catch (error) {
  report.status = 'failed';
  report.failure = String(error);
  throw error;
} finally {
  writeFileSync(path.join(out, 'acceptance.json'), JSON.stringify(report, null, 2) + '\n');
  await browser.close();
}
console.log(JSON.stringify({ status: report.status, cases: report.cases.length, actualSnapshot: report.actualSnapshot, errors: report.errors }));
